"""Builds the dry-run versions of teams-final.sql and teams-rollback.sql.

Each dry run is the real script, unchanged, up to its COMMIT. Instead of committing, it raises an
error whose text reports what the real script would leave behind. The error aborts the transaction,
so a dry run never changes anything. Re-run this file whenever either script changes.
"""
from pathlib import Path

HERE = Path(__file__).parent
SUMMARY = """
do $$
declare
  n_profiles text := 'none';
  msg text;
begin
  -- profiles may already be gone (rollback dry run), so only count it if it exists.
  if to_regclass('public.profiles') is not null then
    execute 'select count(*)::text from public.profiles' into n_profiles;
  end if;
  select format(
    'DRY RUN OK, NOTHING WAS CHANGED (this error is deliberate and rolls everything back). '
    'The real script would leave: %s tasks, %s users, %s profiles, teams tables: %s, teams functions: %s, '
    'policies on tasks: %s, legacy checksum %s.',
    (select count(*) from public.tasks),
    (select count(*) from auth.users),
    n_profiles,
    (select coalesce(string_agg(table_name, ', ' order by table_name), 'none') from information_schema.tables
      where table_schema = 'public' and table_name in ('profiles', 'projects', 'project_members')),
    (select count(*) from pg_proc where pronamespace = 'public'::regnamespace),
    (select count(*) from pg_policies where schemaname = 'public' and tablename = 'tasks'),
    (select md5(coalesce(string_agg(concat_ws('|', id, user_id, title, assignee, deadline, status, project, created_at), ',' order by id), '')) from public.tasks)
  ) into msg;
  raise exception '%', msg;
end;
$$;

rollback;
"""

for name in ("teams-final", "teams-rollback"):
    src = (HERE / f"{name}.sql").read_text()
    head, rest = src.split("\nbegin;\n", 1)
    body = rest[: rest.rindex("\ncommit;\n")]
    out = (
        f"-- DRY RUN of {name}.sql (generated by make-dryruns.py, do not edit by hand).\n"
        f"-- Runs every step of {name}.sql inside one transaction, then stops with an ERROR that starts\n"
        "-- with 'DRY RUN OK, NOTHING WAS CHANGED' and reports what the real script would leave behind.\n"
        "-- That error is deliberate: it aborts the transaction, so nothing is changed.\n"
        "-- Any OTHER error means the real script would fail at that point (and also changes nothing).\n\n"
        "begin;\n" + body + "\n" + SUMMARY
    )
    (HERE / f"{name}-dryrun.sql").write_text(out)
    print(f"wrote {name}-dryrun.sql ({len(out.splitlines())} lines)")
